alter table public.profiles      enable row level security;
alter table public.products      enable row level security;
alter table public.product_costs enable row level security;
alter table public.periods       enable row level security;
alter table public.lines         enable row level security;
alter table public.line_costs    enable row level security;
alter table public.movements     enable row level security;
alter table public.changes       enable row level security;

create policy "own or admin"   on public.profiles      for select to authenticated using (id = auth.uid() or is_admin());
create policy "signed in"      on public.products      for select to authenticated using (is_active());
create policy "see prices"     on public.product_costs for select to authenticated using (has_perm('see_prices'));
create policy "signed in"      on public.periods       for select to authenticated using (is_active());
create policy "signed in"      on public.lines         for select to authenticated using (is_active());
create policy "see prices"     on public.line_costs    for select to authenticated using (has_perm('see_prices'));
create policy "signed in"      on public.movements     for select to authenticated using (is_active());
create policy "admin only"     on public.changes       for select to authenticated using (is_admin());

-- Reads only through the policies above; all writes go through the functions.
revoke insert, update, delete, truncate on all tables in schema public from anon, authenticated;
revoke select on all tables in schema public from anon;
revoke execute on all functions in schema public from public, anon, authenticated;
grant execute on function
  public.is_active(), public.is_admin(), public.has_perm(text),
  public.set_count(bigint, numeric),
  public.add_movement(bigint, text, numeric, text, numeric, boolean),
  public.delete_movement(bigint), public.set_opening(bigint, numeric),
  public.add_product(text, text, numeric, numeric, numeric),
  public.update_product(bigint, text, text, numeric, numeric, numeric, boolean),
  public.close_period(text, text),
  public.admin_create_user(text, text, text, text, text[]),
  public.admin_update_user(uuid, text, text, text[], boolean),
  public.admin_set_password(uuid, text), public.change_my_password(text, text),
  public.mark_changes_seen()
to authenticated;

